/**
 * 连板梯队「高度」—— 梯队**分行口径的唯一实现**（对齐用户参考工具 / 附件 `QQ20260918-230855.png`）。
 *
 * 定义：**「若该股本日涨停，会达到的连板数」**。
 *   · 本日仍涨停（连板股 / 首板股）⇒ 高度 = 该股本日连板数（**不 +1**）；
 *   · 本日未再涨停（断板，**含「首板未续」**）⇒ 高度 = 该股**上一记录交易日**连板数 + 1。
 *
 * 断板股 +1 的来源（2026-09-18 与参考工具逐格对拍，证据
 * `docs/evidence/_probe_ladder_height_caliber.out.json`）：
 *   库里「已实现」的板数本身没错 —— 例如澳弘电子 605058.SH 在 09-11 / 09-14 / 09-15 / 09-16 / 09-17
 *   连续 5 个记录交易日涨停 = 5 板（`server/boardRoster.ts#boardsAt` 逐日核对，连板链无断档）。
 *   但参考工具把它画在 **6 板**行，即该行表达的是「本日若涨停的高度」。逐只核对（断板股全部 +1）：
 *   澳弘电子 5→6、中晶科技 3→4、共达电声 / 中岩大地 / 万向德农 2→3；
 *   当日涨停股两侧**完全一致**（不 +1）：华瓷股份 / 锡华科技 4 板、世联行 / 内蒙新华 3 板。
 *
 * ⚠️ 「首板未续」（`brokenKind === "first"`：上一记录交易日 1 板、本日未涨停）**同样 +1 ⇒ 落到 2 板行**。
 *   2026-09-19 用户明确裁定「首板未续也要 +1」。上一版曾从附件图推断
 *   「参考工具不把首板未续并入 2 板行」（当时可见的 2 板行 8 格全无删除线）——**该推断按裁定作废**：
 *   口径以「若本日涨停的高度」为准，不按参考工具那一列的画法反推。
 *
 * 注意：它**不改** `server/boardRoster.ts#boards`（已实现板数，供 `metrics.maxBoards` 与情绪评分），
 * 两者口径不同 ⇒ 梯队左列最高值可以**高于**「最高板」指标，不是冲突。
 */
export function ladderHeight(row: { boards: number; brokenKind?: "connection" | "first" }): number {
  return row.brokenKind ? row.boards + 1 : row.boards;
}
